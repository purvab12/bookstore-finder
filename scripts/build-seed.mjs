#!/usr/bin/env node
// Turns the OpenStreetMap export in data/osm-raw.json into data/seed.sql.
// Data © OpenStreetMap contributors, licensed under ODbL 1.0.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const CHAINS = [
  "barnes & noble",
  "barnes and noble",
  "books-a-million",
  "books a million",
  "half price books",
  "hudson booksellers",
  "hudson news",
  "kinokuniya",
  "times bookstores",
  "mph",
  "popular bookstore",
  "whsmith",
  "waterstones",
  "foyles",
  "blackwell",
  "chapters",
  "indigo",
  "dymocks",
  "easons",
  "bookazine",
  "amazon books",
  "bookoff",
  "university bookstore",
  "college bookstore",
  "campus bookstore",
];

const raw = JSON.parse(readFileSync("data/osm-raw.json", "utf8"));
const overrides = existsSync("data/tag-overrides.json")
  ? JSON.parse(readFileSync("data/tag-overrides.json", "utf8"))
  : {};

function escapeSql(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function cityFor(lat, lon) {
  if (lat < 2) {
    // Exclude Johor Bahru across the strait from the Singapore bounding box.
    if (lat > 1.462 && lon < 103.83) return null;
    return "singapore";
  }
  if (lat > 41.6) return "chicago";
  return "new-york";
}

function normalizeUrl(value) {
  if (!value) return null;
  const trimmed = value.trim();
  if (!trimmed) return null;
  return /^https?:\/\//i.test(trimmed) ? trimmed : `https://${trimmed}`;
}

function addressFor(tags) {
  const parts = [tags["addr:housenumber"], tags["addr:street"]].filter(Boolean);
  const street = parts.join(" ");
  const city = tags["addr:city"];
  const postcode = tags["addr:postcode"];
  const line = [street, city, postcode].filter(Boolean).join(", ");
  return line || null;
}

function tagsFor(tags) {
  const result = new Set();
  if (tags.second_hand === "yes" || tags["second_hand"] === "only") result.add("used-books");
  if (tags.cafe === "yes" || tags.amenity === "cafe") result.add("cafe");
  if (tags.wheelchair === "yes") result.add("accessible");
  if (tags["books:second_hand"] === "yes") result.add("used-books");
  return result;
}

function isChain(tags, name) {
  if (tags.brand || tags["brand:wikidata"]) return true;
  const lower = name.toLowerCase();
  return CHAINS.some((chain) => lower.includes(chain));
}

function dedupeKey(name, lat, lon) {
  return `${name.toLowerCase().replace(/[^a-z0-9]/g, "")}|${lat.toFixed(4)}|${lon.toFixed(4)}`;
}

const seen = new Set();
const stores = [];
let chains = 0;

for (const element of raw.elements) {
  const tags = element.tags || {};
  const name = tags.name;
  const lat = element.lat ?? element.center?.lat;
  const lon = element.lon ?? element.center?.lon;
  if (!name || lat == null || lon == null) continue;
  const city = cityFor(lat, lon);
  if (!city) continue;

  const key = dedupeKey(name, lat, lon);
  if (seen.has(key)) continue;
  seen.add(key);

  const chain = isChain(tags, name);
  const isBookshop = !/university|college|campus/i.test(name) || !tags.operator;
  void isBookshop;
  if (chain) chains += 1;

  const id = `osm-${element.type}-${element.id}`;
  const tagSet = tagsFor(tags);
  for (const extra of overrides[id] || []) tagSet.add(extra);

  stores.push({
    id,
    type: element.type,
    osmId: String(element.id),
    name,
    city,
    address: addressFor(tags),
    neighborhood: tags["addr:suburb"] || tags["addr:neighbourhood"] || tags["addr:city"] || null,
    lat: Number(lat.toFixed(6)),
    lon: Number(lon.toFixed(6)),
    website: normalizeUrl(tags.website || tags["contact:website"]),
    phone: tags.phone || tags["contact:phone"] || null,
    hours: tags.opening_hours || null,
    isIndie: chain ? 0 : 1,
    sourceUrl: `https://www.openstreetmap.org/${element.type}/${element.id}`,
    tags: [...tagSet],
  });
}

const checkedAt = new Date().toISOString();
const lines = [
  "-- Generated by scripts/build-seed.mjs from data/osm-raw.json",
  "-- Bookshop data © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright)",
  "PRAGMA foreign_keys = ON;",
  "",
];

for (const store of stores) {
  lines.push(
    `INSERT INTO stores (id, osm_type, osm_id, name, city, address, neighborhood, lat, lon, website, phone, opening_hours, is_indie, source, source_url, checked_at) VALUES (` +
      [
        escapeSql(store.id),
        escapeSql(store.type),
        escapeSql(store.osmId),
        escapeSql(store.name),
        escapeSql(store.city),
        escapeSql(store.address),
        escapeSql(store.neighborhood),
        escapeSql(store.lat),
        escapeSql(store.lon),
        escapeSql(store.website),
        escapeSql(store.phone),
        escapeSql(store.hours),
        escapeSql(store.isIndie),
        "'osm'",
        escapeSql(store.sourceUrl),
        escapeSql(checkedAt),
      ].join(", ") +
      `) ON CONFLICT(id) DO UPDATE SET name = excluded.name, city = excluded.city, address = excluded.address, neighborhood = excluded.neighborhood, lat = excluded.lat, lon = excluded.lon, website = excluded.website, phone = excluded.phone, opening_hours = excluded.opening_hours, is_indie = excluded.is_indie, source_url = excluded.source_url, checked_at = excluded.checked_at;`,
  );
  for (const tag of store.tags) {
    lines.push(
      `INSERT OR IGNORE INTO store_tags (store_id, tag, source) VALUES (${escapeSql(store.id)}, ${escapeSql(tag)}, 'osm');`,
    );
  }
}

lines.push("", `-- ${stores.length} bookshops (${chains} flagged as chains)`);
writeFileSync("data/seed.sql", `${lines.join("\n")}\n`);

const byCity = stores.reduce((acc, store) => {
  acc[store.city] = (acc[store.city] || 0) + 1;
  return acc;
}, {});
console.log(`Wrote data/seed.sql: ${stores.length} bookshops`, byCity, `${chains} chains flagged`);
